import { describe, expect, it } from 'vitest'
import { mergeAdjacentCitations, parseFlow, parseReport } from './reportParse'

const STUDY = `# Two-week interview plan

> **Request:** Make me a study plan

## Summary

Spend week 1 on patterns [[1]](https://a.dev/x).

**Assumptions**

- Role: backend intern.

**To tailor this further, tell us:**

- Which company?

## Plan

### Week 1: Core patterns

- [ ] Solve 3 problems _(High priority)_

## Limitations

- Few sources.

## Sources

1. [A](https://a.dev/x) · official docs

---
_Study plan report generated by AgentOS (Alex, Milo, Luna) with m on 2026-11-06 12:00 UTC. Research rounds: 1. Sources consulted: 3. Cited: 1._
`

describe('parseReport', () => {
  it('splits a structured report into summary, preface, body and footer', () => {
    const p = parseReport(STUDY)
    expect(p.structured).toBe(true)
    expect(p.title).toBe('Two-week interview plan')
    expect(p.request).toBe('Make me a study plan')
    expect(p.summary).toBe('Spend week 1 on patterns [[1]](https://a.dev/x).')
    expect(p.preface).toContain('**Assumptions**')
    expect(p.preface).toContain('Which company?')
    expect(p.body.startsWith('## Plan')).toBe(true)
    expect(p.body).toContain('## Limitations')
    expect(p.body).not.toContain('## Sources')
    expect(p.kind).toBe('study_plan')
    expect(p.footer).toMatch(/^_Study plan report generated/)
  })

  it('accepts older reports and falls back for unknown layouts', () => {
    const old = '# Old\n\n> **Request:** q\n\n## Executive summary\n\nText.\n\n## Recommendation\n\nR.\n\n## Sources\n\n1. [x](https://x)\n\n---\n_Generated by AgentOS._\n'
    const p = parseReport(old)
    expect(p.summary).toBe('Text.')
    expect(p.body).toBe('## Recommendation\n\nR.')
    expect(p.kind).toBeNull()
    const raw = parseReport('Just some markdown')
    expect(raw.structured).toBe(false)
    expect(raw.body).toBe('Just some markdown')
  })
})

const EXPLAIN = `# How HTTPS works

> **Request:** Explain HTTPS

## Answer

TLS encrypts HTTP after a handshake [[1]](https://a.dev/x)[[2]](https://b.dev/y).

## Key ideas

- Keys are agreed first.

## A request over HTTPS

\`\`\`mermaid
flowchart LR
  s1["Client hello"] --> s2
  s2["Server 'hello' + cert"] --> s3
  s3["Encrypted HTTP"]
\`\`\`

## Example

\`\`\`bash
# not a heading
## also not a heading
curl -v https://example.com
\`\`\`

## More detail

### Ciphers

Text.

## Evidence

- One [[1]](https://a.dev/x).
- Two [[2]](https://b.dev/y).

## Limitations

- Few sources.

## Sources

1. [A](https://a.dev/x) · official docs

---
_Explanation report generated by AgentOS (Alex, Milo, Luna) with m on 2026-11-06 12:00 UTC. Research rounds: 1. Sources consulted: 3. Cited: 2._
`

describe('answer-first reports', () => {
  it('reads the Answer, splits sections and marks supporting detail as collapsible', () => {
    const p = parseReport(EXPLAIN)
    expect(p.kind).toBe('explanation')
    expect(p.summary).toContain('TLS encrypts HTTP')
    expect(p.sections.map((x) => [x.title, x.collapsible])).toEqual([
      ['Key ideas', false], ['A request over HTTPS', false], ['Example', false],
      ['More detail', true], ['Evidence', true], ['Limitations', true],
    ])
    expect(p.sections[2].markdown).toContain('## also not a heading') // headings inside code fences are content
    expect(p.sections[4].items).toBe(2)
  })

  it('merges adjacent citation chips for the viewer only', () => {
    expect(mergeAdjacentCitations('a [[1]](https://a.dev/x)[[2]](https://b.dev/y). b [[3]](#evidence-D1).'))
      .toBe('a [[1, 2]](https://a.dev/x). b [[3]](#evidence-D1).')
  })

  it('reads the simple flow diagram', () => {
    const code = EXPLAIN.split('```mermaid\n')[1].split('```')[0]
    expect(parseFlow(code)).toEqual(['Client hello', "Server 'hello' + cert", 'Encrypted HTTP'])
    expect(parseFlow('graph TD; A-->B')).toBeNull()
  })
})
